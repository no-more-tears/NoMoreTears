#!/usr/bin/env bash
# Generates infrastructure/docker/.env with random credentials for the local-dev compose files.
# Existing .env is NOT overwritten unless --force is passed.
# Usage: infrastructure/scripts/generate-env.sh [--force]
# Output: infrastructure/docker/.env (template: infrastructure/docker/.env.example)
set -euo pipefail

# shellcheck source=lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

FORCE=false

case "${1:-}" in
    "") ;;
    -f | --force) FORCE=true ;;
    -h | --help) info "Usage: $(basename "$0") [--force]"; exit 0 ;;
    *) fail "unknown option '$1' (use --help)" ;;
esac

ENV_FILE="$DOCKER_DIR/.env"

# Alphanumeric only: values end up in connection strings (';' and '=' are separators),
# in redis-server arguments and in compose interpolation ('$' is special).
# Every kept byte maps to exactly one character, so the distribution has no modulo bias.
random_string() {
    local length="${1:-24}"
    local result=""
    local chunk

    while (( ${#result} < length )); do
        chunk="$(head -c 1024 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9')"
        result+="$chunk"
    done

    printf '%s' "${result:0:length}"
}

[[ -d "$DOCKER_DIR" ]] || fail "directory not found: $DOCKER_DIR"

if [[ -f "$ENV_FILE" && "$FORCE" != true ]]; then
    fail "$ENV_FILE already exists. Use --force to overwrite"
fi

info "Generating .env..."

# umask keeps the generated secrets readable by the current user only.
(
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by infrastructure/scripts/generate-env.sh on $(date '+%Y-%m-%d %H:%M:%S')
# Do not commit this file.

# Shared
IMAGE_TAG=local

# Postgres
POSTGRES_DB=nomoretears
POSTGRES_USER=postgres
POSTGRES_PASSWORD=$(random_string 24)

# pgAdmin
PGADMIN_DEFAULT_EMAIL=admin@noreply.com
PGADMIN_DEFAULT_PASSWORD=$(random_string 24)

# Redis
REDIS_PASSWORD=$(random_string 24)

# Seq
SEQ_ADMIN_PASSWORD=$(random_string 24)

# WebApi (JWT signing key must be at least 32 characters)
JWT_SIGNING_KEY=$(random_string 64)
EOF
) || fail "failed to write $ENV_FILE"

info ".env generated: $ENV_FILE"
info "Note: Postgres, pgAdmin and Seq apply passwords only on first start."
info "If their volumes already exist, run 'docker compose -f <file> down -v' first, or the new passwords will not match."
