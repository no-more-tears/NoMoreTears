# Generates infrastructure\docker\.env with random credentials for the local-dev compose files.
# Existing .env is NOT overwritten unless -Force is passed.
# Expected location: infrastructure\scripts\generate-env.ps1
# Output: infrastructure\docker\.env (template: infrastructure\docker\example.env)
param(
    [switch]$Force
)

$ErrorActionPreference = "Stop"

$DockerDir = Join-Path $PSScriptRoot "..\docker"
$EnvFile = Join-Path $DockerDir ".env"

# Alphanumeric only: values end up in connection strings (`;` and `=` are separators),
# in redis-server arguments and in compose interpolation (`$` is special).
$Alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"

function New-RandomString {
    param([int]$Length = 24)

    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $buffer = New-Object byte[] 1
        $result = New-Object System.Text.StringBuilder
        $limit = 256 - (256 % $Alphabet.Length)

        while ($result.Length -lt $Length) {
            $rng.GetBytes($buffer)
            if ($buffer[0] -lt $limit) {
                [void]$result.Append($Alphabet[$buffer[0] % $Alphabet.Length])
            }
        }

        return $result.ToString()
    } finally {
        $rng.Dispose()
    }
}

if (-not (Test-Path -Path $DockerDir)) {
    Write-Host "Error: directory not found: $DockerDir"
    exit 1
}

if ((Test-Path -Path $EnvFile) -and -not $Force) {
    Write-Host "Error: $EnvFile already exists. Use -Force to overwrite"
    exit 1
}

Write-Host "Generating .env..."

$lines = @(
    "# Generated by infrastructure\scripts\generate-env.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')",
    "# Do not commit this file.",
    "",
    "# Shared",
    "IMAGE_TAG=local",
    "",
    "# Postgres",
    "POSTGRES_DB=nomoretears",
    "POSTGRES_USER=postgres",
    "POSTGRES_PASSWORD=$(New-RandomString -Length 24)",
    "",
    "# pgAdmin",
    "PGADMIN_DEFAULT_EMAIL=admin@noreply.com",
    "PGADMIN_DEFAULT_PASSWORD=$(New-RandomString -Length 24)",
    "",
    "# Redis",
    "REDIS_PASSWORD=$(New-RandomString -Length 24)",
    "",
    "# Seq",
    "SEQ_ADMIN_PASSWORD=$(New-RandomString -Length 24)",
    "",
    "# WebApi (JWT signing key must be at least 32 characters)",
    "JWT_SIGNING_KEY=$(New-RandomString -Length 64)"
)

try {
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($EnvFile, ($lines -join "`n") + "`n", $utf8NoBom)
} catch {
    Write-Host "Error: failed to write $EnvFile"
    Write-Host $_.Exception.Message
    exit 1
}

Write-Host ".env generated: $EnvFile"
Write-Host "Note: Postgres, pgAdmin and Seq apply passwords only on first start."
Write-Host "If their volumes already exist, run 'docker compose -f <file> down -v' first, or the new passwords will not match."