using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using NoMoreTears.Shared.Domain;

namespace NoMoreTears.Shared.Postgres.Extensions;

/// <summary>
///     Shared conventions for entity type configurations.
/// </summary>
public static class EntityTypeBuilderExtensions
{
    /// <summary>
    ///     Name of the shadow property mapped to the Postgres <c>xmin</c> system column.
    /// </summary>
    public const string VersionPropertyName = "Version";

    /// <summary>
    ///     Configures the key and the audit columns of an <see cref="AuditableEntity{TId}"/>.
    ///     Identifiers are generated by the domain, never by the database.
    /// </summary>
    public static EntityTypeBuilder<TEntity> ConfigureAuditableEntity<TEntity, TId>(
        this EntityTypeBuilder<TEntity> builder)
        where TEntity : AuditableEntity<TId>
        where TId : struct
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.HasKey(entity => entity.Id);

        builder.Property(entity => entity.Id)
            .ValueGeneratedNever()
            .IsRequired();

        builder.Property(entity => entity.CreatedAt);
        builder.Property(entity => entity.LastUpdatedAt);
        builder.Property(entity => entity.IsDeleted).IsRequired();
        builder.Property(entity => entity.DeletedAt);

        return builder;
    }

    /// <summary>
    ///     Enables optimistic concurrency through the Postgres <c>xmin</c> system column,
    ///     mapped to a shadow <see cref="uint"/> row version. No column is added to the table.
    /// </summary>
    public static EntityTypeBuilder<TEntity> UseOptimisticConcurrency<TEntity>(
        this EntityTypeBuilder<TEntity> builder)
        where TEntity : class
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.Property<uint>(VersionPropertyName).IsRowVersion();

        return builder;
    }
}